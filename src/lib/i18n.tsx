const dictionaries: Record<Locale, Dict> = { en, uz, ru }

interface I18nContextValue {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export const LOCALES: Locale[] = ['en', 'uz', 'ru']
export const DEFAULT_LOCALE: Locale = 'en'

function getLocaleFromPath(): Locale {
  const path = window.location.pathname
  const match = path.match(/^\/(en|uz|ru)(\/|$)/)
  if (match) return match[1] as Locale
  return DEFAULT_LOCALE
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getLocaleFromPath())

  const setLocale = (l: Locale) => {
    setLocaleState(l)
    const path = window.location.pathname
    const rest = path.replace(/^\/(en|uz|ru)(\/|$)/, '/')
    const newPath = `/${l}${rest === '/' ? '' : rest}`
    window.history.pushState({}, '', newPath)
    window.dispatchEvent(new PopStateEvent('popstate'))
  }

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const t = (key: string): string => {
    return dictionaries[locale][key] ?? dictionaries.en[key] ?? key
  }

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

export function localized(text: { en: string; uz: string; ru: string } | null | undefined, locale: Locale): string {
  if (!text) return ''
  return text[locale] || text.en || text.uz || text.ru || ''
}
